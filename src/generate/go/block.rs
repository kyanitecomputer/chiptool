use anyhow::{bail, Result};
use crate::ir::*;
use super::{GoOptions, camel_case};

/// Render a block as a Go source file.
///
/// All files share opts.package_name so the device file can reference struct
/// types without any cross-package imports.
pub fn render(ir: &IR, block: &Block, block_name: &str, opts: &GoOptions) -> Result<String> {
    let mut out = String::new();

    out.push_str("// Code generated by chiptool; DO NOT EDIT.\n\n");
    out.push_str(&format!("package {}\n\n", opts.package_name));
    out.push_str(&format!("import \"{}\"\n\n", opts.reg_import));

    // Peripheral struct — one per block, identified by a CamelCase name.
    // Base is uintptr so it holds peripheral addresses correctly on both
    // 32-bit (ARM) and 64-bit (ARM64, RISC-V) TamaGo targets.
    let struct_name = camel_case(block_name);
    if let Some(desc) = &block.description {
        out.push_str(&format!("// {} {}\n", struct_name, desc));
    }
    out.push_str(&format!("type {} struct {{\n", struct_name));
    out.push_str("    Base uintptr\n");
    out.push_str("}\n\n");

    // Sort items by byte_offset then name to match Rust generator ordering.
    let mut items: Vec<&BlockItem> = block.items.iter().collect();
    items.sort_by_key(|i| (i.byte_offset, i.name.clone()));

    // Collect unique fieldsets referenced by registers.
    let mut fieldsets: Vec<(String, &FieldSet)> = Vec::new();

    for item in &items {
        match &item.inner {
            BlockItemInner::Register(reg) => {
                render_register_methods(&mut out, ir, item, reg, &struct_name, &mut fieldsets)?;
            }
            BlockItemInner::Block(b) => {
                render_block_accessor(&mut out, item, b, &struct_name)?;
            }
        }
    }

    // Emit fieldset constants (bit positions, masks, enums).
    for (fs_name, fs) in fieldsets {
        out.push_str(&super::fieldset::render(ir, fs, &fs_name)?);
        out.push('\n');
    }

    Ok(out)
}

// ---------------------------------------------------------------------------
// Register methods
// ---------------------------------------------------------------------------

fn render_register_methods<'a>(
    out: &mut String,
    ir: &'a IR,
    item: &BlockItem,
    reg: &Register,
    struct_name: &str,
    fieldsets: &mut Vec<(String, &'a FieldSet)>,
) -> Result<()> {
    let offset = item.byte_offset;
    let method = camel_case(&item.name);
    let go_type = go_type_for_bits(reg.bit_size)?;
    let desc = item.description.as_deref().unwrap_or(&item.name);

    if let Some(array) = &item.array {
        render_array_register_methods(out, ArrayRegCtx {
            struct_name,
            method: &method,
            go_type,
            desc,
            base_offset: offset,
            reg,
        }, array);
    } else {
        render_scalar_register_methods(out, struct_name, &method, go_type, desc, offset, reg);
    }

    // Collect fieldset ref for const block emission.
    if let Some(fs_name) = &reg.fieldset {
        if let Some(fs) = ir.fieldsets.get(fs_name) {
            if !fieldsets.iter().any(|(n, _)| n == fs_name) {
                fieldsets.push((fs_name.clone(), fs));
            }
        }
    }

    Ok(())
}

fn render_scalar_register_methods(
    out: &mut String,
    struct_name: &str,
    method: &str,
    go_type: &str,
    desc: &str,
    offset: u32,
    reg: &Register,
) {
    let (read_fn, write_fn, addr_cast, val_cast) = reg_fns(go_type);

    if matches!(reg.access, Access::Read | Access::ReadWrite) {
        out.push_str(&format!("// Read{} reads {}\n", method, desc));
        out.push_str(&format!(
            "func (p *{}) Read{}() {} {{\n",
            struct_name, method, go_type
        ));
        out.push_str(&format!(
            "    return {}(reg.{}({}(p.Base) + 0x{:04x}))\n",
            go_type, read_fn, addr_cast, offset
        ));
        out.push_str("}\n\n");
    }

    if matches!(reg.access, Access::Write | Access::ReadWrite) {
        out.push_str(&format!("// Write{} writes {}\n", method, desc));
        out.push_str(&format!(
            "func (p *{}) Write{}(val {}) {{\n",
            struct_name, method, go_type
        ));
        out.push_str(&format!(
            "    reg.{}({}(p.Base)+0x{:04x}, {}(val))\n",
            write_fn, addr_cast, offset, val_cast
        ));
        out.push_str("}\n\n");
    }
}

struct ArrayRegCtx<'a> {
    struct_name: &'a str,
    method: &'a str,
    go_type: &'a str,
    desc: &'a str,
    base_offset: u32,
    reg: &'a Register,
}

fn render_array_register_methods(out: &mut String, ctx: ArrayRegCtx<'_>, array: &Array) {
    let ArrayRegCtx { struct_name, method, go_type, desc, base_offset, reg } = ctx;
    let (read_fn, write_fn, addr_cast, val_cast) = reg_fns(go_type);

    match array {
        Array::Regular(a) => {
            let len = a.len;
            let stride = a.stride;

            if matches!(reg.access, Access::Read | Access::ReadWrite) {
                out.push_str(&format!(
                    "// Read{} reads {}[n] (n < {})\n",
                    method, desc, len
                ));
                out.push_str(&format!(
                    "func (p *{}) Read{}(n uintptr) {} {{\n",
                    struct_name, method, go_type
                ));
                out.push_str(&format!(
                    "    return {}(reg.{}({}(p.Base) + 0x{:04x} + n*{}))\n",
                    go_type, read_fn, addr_cast, base_offset, stride
                ));
                out.push_str("}\n\n");
            }

            if matches!(reg.access, Access::Write | Access::ReadWrite) {
                out.push_str(&format!(
                    "// Write{} writes {}[n] (n < {})\n",
                    method, desc, len
                ));
                out.push_str(&format!(
                    "func (p *{}) Write{}(n uintptr, val {}) {{\n",
                    struct_name, method, go_type
                ));
                out.push_str(&format!(
                    "    reg.{}({}(p.Base)+0x{:04x}+n*{}, {}(val))\n",
                    write_fn, addr_cast, base_offset, stride, val_cast
                ));
                out.push_str("}\n\n");
            }
        }
        Array::Cursed(a) => {
            let len = a.offsets.len();
            let offsets_str: Vec<String> =
                a.offsets.iter().map(|o| format!("0x{:04x}", o)).collect();
            let offsets_joined = offsets_str.join(", ");

            if matches!(reg.access, Access::Read | Access::ReadWrite) {
                out.push_str(&format!(
                    "// Read{} reads {}[n] via sparse offsets (n < {})\n",
                    method, desc, len
                ));
                out.push_str(&format!(
                    "func (p *{}) Read{}(n uintptr) {} {{\n",
                    struct_name, method, go_type
                ));
                out.push_str(&format!(
                    "    offsets := [...]uintptr{{{}}}\n",
                    offsets_joined
                ));
                out.push_str(&format!(
                    "    return {}(reg.{}({}(p.Base) + 0x{:04x} + offsets[n]))\n",
                    go_type, read_fn, addr_cast, base_offset
                ));
                out.push_str("}\n\n");
            }

            if matches!(reg.access, Access::Write | Access::ReadWrite) {
                out.push_str(&format!(
                    "// Write{} writes {}[n] via sparse offsets (n < {})\n",
                    method, desc, len
                ));
                out.push_str(&format!(
                    "func (p *{}) Write{}(n uintptr, val {}) {{\n",
                    struct_name, method, go_type
                ));
                out.push_str(&format!(
                    "    offsets := [...]uintptr{{{}}}\n",
                    offsets_joined
                ));
                out.push_str(&format!(
                    "    reg.{}({}(p.Base)+0x{:04x}+offsets[n], {}(val))\n",
                    write_fn, addr_cast, base_offset, val_cast
                ));
                out.push_str("}\n\n");
            }
        }
    }
}

// ---------------------------------------------------------------------------
// Nested-block accessor
// ---------------------------------------------------------------------------

fn render_block_accessor(
    out: &mut String,
    item: &BlockItem,
    b: &BlockItemBlock,
    struct_name: &str,
) -> Result<()> {
    let nested_struct = camel_case(&b.block);
    let method = camel_case(&item.name);
    let desc = item.description.as_deref().unwrap_or(&item.name);

    if let Some(array) = &item.array {
        // Array of nested blocks — emit an indexed accessor.
        match array {
            Array::Regular(a) => {
                let len = a.len;
                let stride = a.stride;
                out.push_str(&format!("// {} returns {}[n] (n < {})\n", method, desc, len));
                out.push_str(&format!(
                    "func (p *{}) {}(n uintptr) {} {{\n",
                    struct_name, method, nested_struct
                ));
                out.push_str(&format!(
                    "    return {}{{Base: p.Base + 0x{:04x} + n*{}}}\n",
                    nested_struct, item.byte_offset, stride
                ));
                out.push_str("}\n\n");
            }
            Array::Cursed(a) => {
                let len = a.offsets.len();
                let offsets_str: Vec<String> =
                    a.offsets.iter().map(|o| format!("0x{:04x}", o)).collect();
                let offsets_joined = offsets_str.join(", ");
                out.push_str(&format!(
                    "// {} returns {}[n] via sparse offsets (n < {})\n",
                    method, desc, len
                ));
                out.push_str(&format!(
                    "func (p *{}) {}(n uintptr) {} {{\n",
                    struct_name, method, nested_struct
                ));
                out.push_str(&format!(
                    "    offsets := [...]uintptr{{{}}}\n",
                    offsets_joined
                ));
                out.push_str(&format!(
                    "    return {}{{Base: p.Base + 0x{:04x} + offsets[n]}}\n",
                    nested_struct, item.byte_offset
                ));
                out.push_str("}\n\n");
            }
        }
    } else {
        // Scalar nested block.
        out.push_str(&format!("// {} returns {}\n", method, desc));
        out.push_str(&format!(
            "func (p *{}) {}() {} {{\n",
            struct_name, method, nested_struct
        ));
        out.push_str(&format!(
            "    return {}{{Base: p.Base + 0x{:04x}}}\n",
            nested_struct, item.byte_offset
        ));
        out.push_str("}\n\n");
    }
    Ok(())
}

