/// Return (read_fn, write_fn, addr_cast, val_cast) for the given Go register type.
///
/// TamaGo's reg package uses:
///   - reg.Read(addr uint32) uint32 / reg.Write(addr uint32, val uint32)
///   - reg.Read64(addr uint64) uint64 / reg.Write64(addr uint64, val uint64)
///
/// Addresses are stored as `uintptr` in the struct, so we cast on each call.
/// The val_cast ensures sub-32-bit types (uint8, uint16) are widened to uint32
/// before being passed to reg.Write.
fn reg_fns(go_type: &str) -> (&'static str, &'static str, &'static str, &'static str) {
    if go_type == "uint64" {
        ("Read64", "Write64", "uint64", "uint64")
    } else {
        ("Read", "Write", "uint32", "uint32")
    }
}

fn go_type_for_bits(bit_size: u32) -> Result<&'static str> {
    match bit_size {
        8 => Ok("uint8"),
        16 => Ok("uint16"),
        32 => Ok("uint32"),
        64 => Ok("uint64"),
        _ => bail!("Unsupported register bit size: {}", bit_size),
    }
}
