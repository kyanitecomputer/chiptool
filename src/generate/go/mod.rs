/// Format a potentially multi-line description as Go comment lines.
///
/// Each line of `desc` is prefixed with `// ` so that newlines in YAML
/// descriptions don't produce invalid Go syntax.
pub fn go_comment(desc: &str) -> String {
    let mut out = String::new();
    for line in desc.lines() {
        out.push_str("// ");
        out.push_str(line);
        out.push('\n');
    }
    out
}

/// Convert snake_case or other names to CamelCase
pub fn camel_case(s: &str) -> String {
    let mut result = String::new();
    let mut capitalize = true;
    for c in s.chars() {
        if c == '_' || c == ':' {
            capitalize = true;
        } else if capitalize {
            result.push(c.to_ascii_uppercase());
            capitalize = false;
        } else {
            result.push(c);
        }
    }
    result
}

/// Options for Go code generation (TamaGo-compatible)
pub struct GoOptions {
    /// Package name for generated code (default: "pac")
    pub package_name: String,
    /// Import path for register access (default: "tamago/reg")
    pub reg_import: String,
}

impl Default for GoOptions {
    fn default() -> Self {
        Self {
            package_name: "pac".to_string(),
            reg_import: "tamago/reg".to_string(),
        }
    }
}

pub struct GoGenerator;

impl CodeGenerator for GoGenerator {
    type Output = String;
    type Options = GoOptions;

    fn generate(&self, ir: &IR, opts: &Self::Options) -> Result<Vec<(String, Self::Output)>> {
        let mut files = Vec::new();

        // Collect fieldsets referenced by any block so we can emit them once
        // in a dedicated file rather than inline in each block file.
        // This prevents duplicate `const` declarations when multiple blocks
        // share the same fieldset (e.g. fmc_v1::SPICTRL used by FMC and SPI).
        let mut referenced_fieldsets: BTreeSet<String> = Default::default();
        for block in ir.blocks.values() {
            for item in &block.items {
                if let BlockItemInner::Register(reg) = &item.inner {
                    if let Some(fs_name) = &reg.fieldset {
                        referenced_fieldsets.insert(fs_name.clone());
                    }
                }
            }
        }

        // Generate per-block Go files (methods only, no inline fieldsets).
        for (name, block) in &ir.blocks {
            let filename = format!("{}.gen.go", name.to_lowercase().replace("::", "_"));
            let content = block::render_no_fieldsets(ir, block, name, opts)?;
            files.push((filename, content));
        }

        // Generate a single fieldsets.gen.go with all unique fieldset consts.
        if !referenced_fieldsets.is_empty() {
            let mut fs_content = String::new();
            fs_content.push_str("// Code generated by chiptool; DO NOT EDIT.\n\n");
            fs_content.push_str(&format!("package {}\n\n", opts.package_name));
            for fs_name in &referenced_fieldsets {
                if let Some(fs) = ir.fieldsets.get(fs_name) {
                    fs_content.push_str(&fieldset::render(ir, fs, fs_name)?);
                    fs_content.push('\n');
                }
            }
            files.push(("fieldsets.gen.go".to_string(), fs_content));
        }

        // Generate a single device.gen.go with peripheral base-address
        // constants and IRQ numbers.
        if !ir.devices.is_empty() {
            let mut device_content = String::new();
            device_content.push_str("// Code generated by chiptool; DO NOT EDIT.\n\n");
            device_content.push_str(&format!("package {}\n\n", opts.package_name));
            for device in ir.devices.values() {
                device_content.push_str(&device::render(ir, device, opts)?);
            }
            files.push(("device.gen.go".to_string(), device_content));
        }

        Ok(files)
    }
}
